import subprocess
import sys
import textwrap


def test_base_toolkit_imports_without_mcp_server_fastmcp():
    code = textwrap.dedent(
        """
        import mcp.server

        if hasattr(mcp.server, "FastMCP"):
            del mcp.server.FastMCP

        import camel.toolkits.base as base

        assert base.BaseToolkit is not None
        """
    )
    result = subprocess.run(
        [sys.executable, "-c", code],
        capture_output=True,
        text=True,
        check=False,
    )
    assert result.returncode == 0, result.stderr
